/**
 * E-invoice PDF (browser only). Loads the invoice through the server action,
 * which checks the signed-in account, then builds and downloads the PDF.
 */
import { getEInvoiceAction, type EInvoice } from "@/app/actions/leasing";
import { formatPHDate } from "@/lib/ph-date";
import { addDays, peso } from "@/lib/leasing";

const STATUS: Record<EInvoice["status"], string> = { PAID: "Paid", DUE: "Due", OVERDUE: "Overdue", VOID: "Void" };

export async function downloadInvoicePdf(invoiceId: string): Promise<string | null> {
  const res = await getEInvoiceAction(invoiceId);
  if (!res.success) return res.error;
  const inv = res.data;

  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import("jspdf"), import("jspdf-autotable")]);
  const doc = new jsPDF();
  const left = 14;
  const right = 196;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(30, 30, 30);
  doc.text("SR Mall", left, 20);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(110, 110, 110);
  doc.text("Management Office", left, 26);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(30, 30, 30);
  doc.text("E-INVOICE", right, 20, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(80, 80, 80);
  doc.text(inv.invoiceNumber, right, 26, { align: "right" });
  doc.text(`Status: ${STATUS[inv.status]}`, right, 31, { align: "right" });

  doc.setDrawColor(225, 225, 225);
  doc.line(left, 37, right, 37);

  // Billed to / details
  doc.setFontSize(9);
  doc.setTextColor(110, 110, 110);
  doc.text("BILLED TO", left, 45);
  doc.text("DETAILS", 120, 45);
  doc.setTextColor(30, 30, 30);
  doc.setFontSize(10);
  const billed = [
    inv.billedTo.companyName || inv.billedTo.shopName,
    inv.billedTo.companyName ? `Store: ${inv.billedTo.shopName}` : null,
    inv.billedTo.contact,
    inv.billedTo.email,
    inv.billedTo.address,
  ].filter(Boolean) as string[];
  let y = 51;
  for (const line of billed) {
    const wrapped = doc.splitTextToSize(line, 95) as string[];
    doc.text(wrapped, left, y);
    y += wrapped.length * 5;
  }

  const period =
    inv.periodStart && inv.periodEnd
      ? `${formatPHDate(inv.periodStart)} to ${formatPHDate(addDays(inv.periodEnd, -1))}`
      : null;
  const details: [string, string][] = [
    ["Issued", formatPHDate(inv.issuedAt)],
    ["Space", inv.unitId ? `Unit ${inv.unitId}${inv.floor ? `, ${inv.floor} floor` : ""}` : "-"],
    ...(period ? ([["Billing period", period]] as [string, string][]) : []),
    ...(inv.paidAt ? ([["Paid on", formatPHDate(inv.paidAt)]] as [string, string][]) : [["Due", formatPHDate(inv.dueDate)]] as [string, string][]),
    ...(inv.paymentMethod ? ([["Method", inv.paymentMethod]] as [string, string][]) : []),
    ...(inv.referenceNo ? ([["Reference", inv.referenceNo]] as [string, string][]) : []),
  ];
  let dy = 51;
  for (const [k, v] of details) {
    doc.setTextColor(110, 110, 110);
    doc.text(k, 120, dy);
    doc.setTextColor(30, 30, 30);
    doc.text(doc.splitTextToSize(v, 45) as string[], 151, dy);
    dy += v.length > 28 ? 10 : 6;
  }

  autoTable(doc, {
    startY: Math.max(y, dy) + 6,
    head: [["Description", "Qty", "Unit price", "Amount"]],
    body: inv.lines.map((l) => [l.description, String(l.quantity), peso(l.unitPrice), peso(l.amount)]),
    foot: [["", "", "Total", peso(inv.total)]],
    theme: "plain",
    styles: { fontSize: 9, cellPadding: 3, textColor: [30, 30, 30] },
    headStyles: { fillColor: [244, 244, 245], fontStyle: "bold" },
    footStyles: { fontStyle: "bold" },
    columnStyles: { 1: { halign: "right", cellWidth: 14 }, 2: { halign: "right", cellWidth: 34 }, 3: { halign: "right", cellWidth: 34 } },
    didParseCell: (d) => {
      if ((d.section === "head" || d.section === "foot") && d.column.index > 0) d.cell.styles.halign = "right";
    },
  });

  const end = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14;
  doc.setFontSize(8);
  doc.setTextColor(110, 110, 110);
  doc.text(
    inv.status === "PAID"
      ? "Payment received at the SR Mall management office. This e-invoice was generated by the system."
      : "Pay at the SR Mall management office. This e-invoice was generated by the system.",
    left,
    end,
  );

  doc.save(`${inv.invoiceNumber}.pdf`);
  return null;
}
